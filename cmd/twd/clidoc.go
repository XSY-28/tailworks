package main

import (
	"bytes"
	"fmt"
	"strings"
)

// cliReference renders docs/cli.md (issue #51): every command in `twd
// help`'s groups, and under it the `twd <path> --help` output of each
// command path the completion tree knows (`twd kv`, `twd kv get`, …);
// a subcommand's section has only its flags.
// TestCLIReferenceUpToDate fails when docs/cli.md differs; `make cli-docs`
// rewrites it. Since the text is the --help output itself, the reference
// can't drift from it.
func cliReference() string {
	var b strings.Builder
	b.WriteString("# CLI reference\n\n")
	b.WriteString("<!-- Generated by `make cli-docs` from cmd/twd's commands table and flag sets. Do not edit. -->\n\n")
	b.WriteString("Every `twd` command and subcommand with its `--help` output: the usage line\n")
	b.WriteString("and each flag with its default. `twd help` lists the commands by group;\n")
	b.WriteString("`twd <command> --help` prints one of these sections. Every command also\n")
	b.WriteString("takes `--state-dir` (default `$TWD_STATE_DIR` or `~/.twd`) and `--json`\n")
	b.WriteString("([cli-json.md](cli-json.md)).\n")

	tree := buildCompletionTree()
	titles, groups := groupedCommands()
	for i, title := range titles {
		fmt.Fprintf(&b, "\n## %s\n", title)
		for _, c := range groups[i] {
			fmt.Fprintf(&b, "\n### twd %s\n\n%s\n", c.name, helpLine(c))
			for _, p := range tree.paths() {
				if p != c.name && !strings.HasPrefix(p, c.name+" ") {
					continue
				}
				text := cliHelpText(c, strings.Fields(p)[1:])
				if p != c.name {
					// The description and usage line are the command's
					// (above); a subcommand adds its own flag set.
					i := strings.Index(text, "\nflags:\n")
					if i < 0 {
						continue
					}
					text = text[i+1:]
					fmt.Fprintf(&b, "\n#### twd %s\n", p)
				}
				b.WriteString("\n```text\n")
				b.WriteString(text)
				b.WriteString("```\n")
			}
		}
	}
	return b.String()
}

// cliHelpText is `twd <c> <sub…> --help`'s output.
func cliHelpText(c command, sub []string) string {
	saved := jsonOut
	defer func() { jsonOut = saved }()
	var out bytes.Buffer
	commandHelp(&out, c, append(append([]string{}, sub...), "--help"))
	s := strings.TrimRight(out.String(), "\n") + "\n"
	// up --host-id defaults to this machine's hostname: the reference
	// says so instead of naming the machine that generated it.
	s = strings.ReplaceAll(s, fmt.Sprintf("(default %q)", defaultHostID()), `(default "h-<hostname>")`)
	return strings.ReplaceAll(s, "```", "'''")
}
