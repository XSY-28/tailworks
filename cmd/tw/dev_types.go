package main

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"path/filepath"
)

// typesHeader starts the first line of a file plain `tw types` wrote.
// `tw types --remote` writes typesRemoteHeader instead, so tw dev (which
// sees only local secret names) leaves that file alone.
const (
	typesHeader       = "// Generated by `tw types` from "
	typesRemoteHeader = "// Generated by `tw types --remote` from "
)

// typesMarkRemote rewrites genTypes' header for `tw types --remote`.
func typesMarkRemote(src []byte) []byte {
	return bytes.Replace(src, []byte(typesHeader), []byte(typesRemoteHeader), 1)
}

// devRefreshTypes keeps a tw-generated worker-configuration.d.ts in step
// with the config while tw dev runs (#474): on start and on each reload it
// rewrites the file when genTypes' output differs. It never creates the
// file, and never touches one that plain `tw types` didn't write (a
// hand-written file, `tw types --remote`'s, or one typed for an --env).
// It does nothing when tw dev itself runs with --env, --wrangler or
// --from-wrangler-out (the caller skips --once). Errors are warnings: the
// file is an editor aid, and `tw types --check` stays the CI gate. It
// reports whether it wrote the file.
func devRefreshTypes(a *app, warn io.Writer) bool {
	if a.Opts.Env != "" || a.Opts.Wrangler || a.Opts.WranglerOut != "" {
		return false
	}
	path := filepath.Join(a.Dir, typesFile)
	st, err := os.Lstat(path)
	if err != nil || !st.Mode().IsRegular() {
		return false
	}
	cur, err := os.ReadFile(path)
	if err != nil || !bytes.HasPrefix(cur, []byte(typesHeader)) || bytes.Contains(cur, []byte("\n// Environment: --env ")) {
		return false
	}
	secrets, err := typesSecrets(a)
	if err != nil {
		fmt.Fprintf(warn, "! %s not refreshed: %v\n", typesFile, err)
		return false
	}
	src, _ := genTypes(a, a.Dir, secrets)
	if bytes.Equal(cur, src) {
		return false
	}
	if err := os.WriteFile(path, src, st.Mode().Perm()); err != nil {
		fmt.Fprintf(warn, "! %s not refreshed: %v\n", typesFile, err)
		return false
	}
	fmt.Fprintf(warn, "  types %s refreshed from the config (as `tw types` writes it)\n", typesFile)
	return true
}
